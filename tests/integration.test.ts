import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createHash, randomBytes } from 'node:crypto';
import { mkdtemp, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { DatabaseSync } from 'node:sqlite';

test('isolated route integration: auth, tenant ownership, CORS, challenge replay, central consume and rotation', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'bicaptcha-integration-'));
  const dbPath = join(directory, 'test.db');
  const sqlite = new DatabaseSync(dbPath);
  for (const name of ['202611150000_baseline', '202611150001_security_v2']) sqlite.exec(await readFile(`prisma/migrations/${name}/migration.sql`, 'utf8'));
  sqlite.close();
  Object.assign(process.env, { NODE_ENV: 'test', BICAPTCHA_STATE: 'memory', APP_ORIGIN: 'https://dashboard.example.com', DATABASE_URL: `file:${dbPath}`, JWT_SECRET: randomBytes(32).toString('hex'), BICAPTCHA_SECRET: randomBytes(32).toString('hex'), BICAPTCHA_VERIFY_SECRET: randomBytes(32).toString('hex') });
  const { prisma } = await import('../src/lib/prisma');
  const login = await import('../src/app/api/auth/login/route');
  const register = await import('../src/app/api/auth/register/route');
  const logout = await import('../src/app/api/auth/logout/route');
  const sites = await import('../src/app/api/sites/route');
  const rotate = await import('../src/app/api/sites/[id]/rotate-secret/route');
  const dns = await import('../src/app/api/sites/[id]/verify/route');
  const challenge = await import('../src/app/api/bi-captcha/challenge/route');
  const verify = await import('../src/app/api/bi-captcha/verify/route');
  const siteverify = await import('../src/app/api/bi-captcha/siteverify/route');
  const me = await import('../src/app/api/auth/me/route');
  const request = (path: string, body?: unknown, headers: Record<string, string> = {}) => new Request(`https://api.example.com${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { origin: 'https://dashboard.example.com', ...(body === undefined ? {} : { 'content-type': 'application/json' }), ...headers }, body: body === undefined ? undefined : JSON.stringify(body) });
  const account = { email: 'owner@example.com', password: 'valid-long-password-123' };
  try {
    assert.equal((await register.POST(request('/api/auth/register', account, { origin: 'https://evil.example.com' }))).status, 403);
    assert.equal((await register.POST(request('/api/auth/register', account))).status, 200);
    const loginResponse = await login.POST(request('/api/auth/login', account));
    assert.equal(loginResponse.status, 200);
    const setCookie = loginResponse.headers.get('set-cookie')!;
    assert.ok(setCookie.includes('HttpOnly') && setCookie.includes('Path=/') && setCookie.includes('SameSite=lax'));
    const cookie = setCookie.split(';')[0];
    assert.equal((await me.GET(request('/api/auth/me', undefined, { cookie }))).status, 200);
    assert.equal((await me.GET(request('/api/auth/me', undefined, { cookie: `${cookie}; ${cookie}` }))).status, 401);
    assert.equal((await sites.POST(request('/api/sites', { domain: 'example.com' }, { cookie, origin: 'https://evil.example.com' }))).status, 403);
    const createdResponse = await sites.POST(request('/api/sites', { domain: 'EXAMPLE.COM.' }, { cookie }));
    assert.equal(createdResponse.status, 201);
    const created = await createdResponse.json();
    assert.equal(created.site.domain, 'example.com');
    assert.ok(created.verificationSecret.startsWith('bcs_'));
    for (const forbidden of ['secretKey', 'verificationSecretHash', 'userId']) assert.equal(forbidden in created.site, false);
    const listed = await (await sites.GET(request('/api/sites', undefined, { cookie }))).json();
    assert.equal(JSON.stringify(listed).includes(created.verificationSecret), false);
    assert.equal(JSON.stringify(listed).includes('secretKey'), false);
    const key = created.site.siteKey;
    assert.equal((await challenge.POST(request('/challenge', { siteKey: key, action: 'contact' }, { origin: 'https://www.example.com' }))).status, 403);
    await prisma.site.update({ where: { id: created.site.id }, data: { isVerified: true } }); // Fixture, never live DNS/DB.
    await prisma.user.create({ data: { id: 'other-user', email: 'other@example.com', password: 'unused' } });
    const { issueSession } = await import('../src/lib/security/auth');
    const otherCookie = `bicaptcha_session=${await issueSession('other-user')}`;
    const params = { params: Promise.resolve({ id: created.site.id }) };
    assert.equal((await dns.POST(request('/verify', {}, { cookie: otherCookie }), params)).status, 404);
    assert.equal((await rotate.POST(request('/rotate', {}, { cookie: otherCookie }), params)).status, 404);
    const preflight = (origin: string, method = 'POST', header = 'content-type') => challenge.OPTIONS(new Request(`https://api.example.com/api/bi-captcha/challenge?siteKey=${key}`, { method: 'OPTIONS', headers: { origin, 'access-control-request-method': method, 'access-control-request-headers': header } }));
    const allowed = await preflight('https://shop.example.com');
    assert.equal(allowed.status, 204);
    assert.equal(allowed.headers.get('access-control-allow-origin'), 'https://shop.example.com');
    assert.equal(allowed.headers.get('access-control-allow-credentials'), null);
    assert.equal((await preflight('https://evil-example.com')).headers.get('access-control-allow-origin'), null);
    assert.notEqual((await preflight('https://shop.example.com', 'POST', 'authorization')).status, 204);
    assert.notEqual((await preflight('https://shop.example.com:8443')).status, 204);
    const body = { siteKey: key, action: 'contact' };
    const headers = { origin: 'https://shop.example.com', 'x-forwarded-for': 'arbitrary attacker value' };
    const challengeResponse = await challenge.POST(request('/challenge', body, headers));
    assert.equal(challengeResponse.status, 200);
    assert.equal(challengeResponse.headers.get('access-control-allow-origin'), headers.origin);
    const c = await challengeResponse.json();
    let nonce = 0;
    while (!createHash('sha256').update(`${c.challenge}:${nonce}`).digest('hex').startsWith('0000')) nonce++;
    const proof = { ...body, challenge: c.challenge, nonce: String(nonce), telemetry: { webdriver: true } };
    assert.notEqual((await verify.POST(request('/verify', { ...proof, trustPassSignature: 'legacy', trustPassPublicKey: 'legacy' }, headers))).status, 200);
    assert.notEqual((await verify.POST(request('/verify', { ...proof, action: 'different' }, headers))).status, 200);
    const responses = await Promise.all(Array.from({ length: 10 }, () => verify.POST(request('/verify', proof, headers))));
    const successes = responses.filter(r => r.status === 200);
    assert.equal(successes.length, 1);
    const token = (await successes[0].json()).token;
    const consumeBody = { ...body, token, hostname: 'shop.example.com' };
    const credential = { authorization: `Bearer ${created.verificationSecret}` };
    assert.equal((await siteverify.POST(request('/siteverify', consumeBody))).status, 403);
    assert.notEqual((await siteverify.POST(request('/siteverify', { ...consumeBody, action: 'different' }, credential))).status, 200);
    const rotated = await (await rotate.POST(request('/rotate', {}, { cookie }), params)).json();
    assert.equal((await siteverify.POST(request('/siteverify', consumeBody, credential))).status, 403);
    const consumers = await Promise.all(Array.from({ length: 10 }, () => siteverify.POST(request('/siteverify', consumeBody, { authorization: `Bearer ${rotated.verificationSecret}` }))));
    assert.equal(consumers.filter(r => r.status === 200).length, 1);
    assert.equal(consumers[0].headers.get('access-control-allow-origin'), null);
    for (let i = 0; i < 4; i++) assert.equal((await login.POST(request('/login', { ...account, password: 'wrong-password-long' }))).status, 401);
    assert.equal((await login.POST(request('/login', account))).status, 429);
    const loggedOut = await logout.POST(request('/logout', {}, { cookie }));
    assert.ok(loggedOut.headers.get('set-cookie')?.includes('Max-Age=0'));
    assert.ok(loggedOut.headers.get('set-cookie')?.includes('Path=/'));
    assert.equal(await prisma.validationLog.count(), 0); // Privacy default: metrics off.
  } finally { await prisma.$disconnect(); }
});
